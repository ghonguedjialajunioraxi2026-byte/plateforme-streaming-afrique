CREATE TABLE follows (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    follower_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    followed_id     BIGINT NOT NULL REFERENCES creator_profiles (id) ON DELETE RESTRICT,
    CONSTRAINT uk_follows_follower_followed UNIQUE (follower_id, followed_id)
);

CREATE INDEX idx_follows_follower  ON follows (follower_id);
CREATE INDEX idx_follows_followed  ON follows (followed_id);
