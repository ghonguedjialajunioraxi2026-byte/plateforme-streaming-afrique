CREATE TABLE clips (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    creator_id          BIGINT NOT NULL REFERENCES creator_profiles (id) ON DELETE RESTRICT,
    stream_id           BIGINT REFERENCES streams (id) ON DELETE RESTRICT,
    video_id            BIGINT REFERENCES videos (id) ON DELETE RESTRICT,
    title               VARCHAR(150) NOT NULL,
    clip_url            VARCHAR(500) NOT NULL,
    storage_key         VARCHAR(500),
    thumbnail_url       VARCHAR(500),
    starts_at_seconds   INTEGER NOT NULL,
    duration_seconds    INTEGER NOT NULL,
    visibility          VARCHAR(20) NOT NULL,
    processing_status   VARCHAR(20) NOT NULL,
    deleted             BOOLEAN NOT NULL,
    share_slug          VARCHAR(20) NOT NULL,
    CONSTRAINT uk_clips_share_slug    UNIQUE (share_slug),
    CONSTRAINT ck_clips_xor_source    CHECK ((stream_id IS NULL) <> (video_id IS NULL)),
    CONSTRAINT ck_clips_visibility    CHECK (visibility IN ('PUBLIC', 'UNLISTED', 'PRIVATE')),
    CONSTRAINT ck_clips_processing    CHECK (processing_status IN ('UPLOADED', 'PROCESSING', 'READY', 'FAILED')),
    CONSTRAINT ck_clips_segment       CHECK (starts_at_seconds >= 0 AND duration_seconds > 0)
);

CREATE INDEX idx_clips_creator              ON clips (creator_id);
CREATE INDEX idx_clips_creator_visibility   ON clips (creator_id, visibility);
CREATE INDEX idx_clips_stream               ON clips (stream_id);
CREATE INDEX idx_clips_video                ON clips (video_id);
