-- ============================================================
-- V14__statistics.sql — agrégats immuables par périmètre/période (7.23).
-- Dépend de : V3 (categories, creator_profiles), V4 (streams), V5 (videos).
-- 1 ligne = 1 métrique × 1 périmètre × 1 période × 1 grain (HOUR/DAY/WEEK/
-- MONTH, rollups). Temps réel en Redis, brut dans les tables sources :
-- cette table est la SEULE source des courbes. Passé jamais réécrit.
-- Anti-doublon : garde applicative (finder) + futurs index partiels DDL
-- par scope (l'UNIQUE multi-colonnes à NULL ne bloque rien en SQL).
-- ============================================================

CREATE TABLE stat_snapshots (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    scope_type          VARCHAR(20) NOT NULL,
    scope_chain_id      BIGINT REFERENCES creator_profiles (id) ON DELETE RESTRICT,
    scope_stream_id     BIGINT REFERENCES streams (id) ON DELETE RESTRICT,
    scope_video_id      BIGINT REFERENCES videos (id) ON DELETE RESTRICT,
    scope_category_id   BIGINT REFERENCES categories (id) ON DELETE RESTRICT,
    granularity         VARCHAR(10) NOT NULL,
    period_start        TIMESTAMPTZ NOT NULL,
    period_end          TIMESTAMPTZ NOT NULL,
    metric              VARCHAR(20) NOT NULL,
    metric_value        BIGINT NOT NULL,
    CONSTRAINT uk_stats_scope_period_metric UNIQUE (scope_type, scope_chain_id, scope_stream_id,
        scope_video_id, scope_category_id, period_start, period_end, metric),
    CONSTRAINT ck_stats_scope   CHECK (scope_type IN ('PLATFORM', 'CHAIN', 'STREAM', 'VIDEO', 'CATEGORY')),
    CONSTRAINT ck_stats_grain   CHECK (granularity IN ('HOUR', 'DAY', 'WEEK', 'MONTH')),
    CONSTRAINT ck_stats_period  CHECK (period_end > period_start),
    CONSTRAINT ck_stats_metric  CHECK (metric IN ('PEAK_VIEWERS', 'VIEWS', 'WATCH_SECONDS', 'FOLLOWS_GAINED',
        'SUBSCRIPTIONS', 'REVENUE_COINS', 'GIFTS_COUNT')),
    CONSTRAINT ck_stats_value   CHECK (metric_value >= 0)
);

CREATE INDEX idx_stats_scope_period ON stat_snapshots (scope_type, period_start);
