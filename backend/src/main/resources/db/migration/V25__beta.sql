-- 1. beta_invitations : accès contrôlé (UN seul mécanisme, §4).
--    Le code N'EST JAMAIS stocké en clair : seule son empreinte SHA-256
--    hex (64 car.) persiste (même motif que les stream keys) ; le code
--    en clair n'est montré qu'UNE fois à sa création. Code lié à UN email
--    (pas de partage) + expiration + usage unique.
-- 2. beta_feedback : retours bêta-testeurs (BUG/UX/SUGGESTION/…),
--    workflow OPEN → TRIAGED → IN_PROGRESS → FIXED → VERIFIED → CLOSED.
--    Contexte technique volontairement MINIMAL (route, version app,
--    appareil — jamais mot de passe/token/contenu privé).
-- ============================================================

CREATE TABLE beta_invitations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    email           VARCHAR(150) NOT NULL,
    code_hash       VARCHAR(64) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    expires_at      TIMESTAMPTZ NOT NULL,
    accepted_at     TIMESTAMPTZ,
    accepted_user_id BIGINT,
    created_by_admin_id BIGINT,
    note            VARCHAR(280),
    CONSTRAINT ck_beta_inv_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REVOKED')),
    CONSTRAINT uk_beta_inv_code_hash UNIQUE (code_hash),
    CONSTRAINT fk_beta_inv_user FOREIGN KEY (accepted_user_id)
        REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_beta_inv_email ON beta_invitations (email);
CREATE INDEX idx_beta_inv_status ON beta_invitations (status);

CREATE TABLE beta_feedback (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    reporter_id     BIGINT NOT NULL,
    category        VARCHAR(20) NOT NULL,
    title           VARCHAR(140) NOT NULL,
    description     VARCHAR(4000) NOT NULL,
    route           VARCHAR(200),
    app_version     VARCHAR(40),
    device          VARCHAR(120),
    status          VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    priority        VARCHAR(5),
    CONSTRAINT ck_beta_fb_category CHECK (category IN
        ('BUG', 'UX', 'SUGGESTION', 'PERFORMANCE', 'STREAMING',
         'CHAT', 'PAYMENT', 'OTHER')),
    CONSTRAINT ck_beta_fb_status CHECK (status IN
        ('OPEN', 'TRIAGED', 'IN_PROGRESS', 'FIXED', 'VERIFIED', 'CLOSED')),
    CONSTRAINT ck_beta_fb_priority CHECK (priority IS NULL OR priority IN
        ('P0', 'P1', 'P2', 'P3')),
    CONSTRAINT fk_beta_fb_reporter FOREIGN KEY (reporter_id)
        REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_beta_fb_reporter ON beta_feedback (reporter_id);
CREATE INDEX idx_beta_fb_status ON beta_feedback (status);
CREATE INDEX idx_beta_fb_category ON beta_feedback (category);
