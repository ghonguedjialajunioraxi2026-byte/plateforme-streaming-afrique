-- ============================================================
-- V19__coin_packages.sql — catalogue des packs de coins (étape 14).
-- Dépend de : aucune (table autonome, référencée par packageId
-- côté applicatif, sans FK depuis payments).
-- SOURCE DE VÉRITÉ SERVEUR : prix, devise et quantité relus ici,
-- jamais envoyés par le frontend.
-- ============================================================

CREATE TABLE coin_packages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    name            VARCHAR(100) NOT NULL,
    coins_amount    BIGINT NOT NULL,
    price_amount    NUMERIC(19, 4) NOT NULL,
    -- VARCHAR(3) et non CHAR(3) : l'entité mappe un String (validate Hibernate).
    price_currency  VARCHAR(3) NOT NULL,
    active          BOOLEAN NOT NULL,
    sort_order      INTEGER NOT NULL,
    description     VARCHAR(500),
    CONSTRAINT ck_coin_packages_amounts   CHECK (coins_amount > 0 AND price_amount > 0),
    CONSTRAINT ck_coin_packages_currency  CHECK (price_currency ~ '^[A-Z]{3}$')
);

-- Catalogue actif trié (vitrine d'achat) : packages actifs par ordre d'affichage.
CREATE INDEX idx_coin_packages_active_order
    ON coin_packages (active, sort_order);
