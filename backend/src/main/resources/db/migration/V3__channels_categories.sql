CREATE TABLE categories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    name            VARCHAR(50) NOT NULL,
    slug            VARCHAR(60) NOT NULL,
    description     VARCHAR(500),
    image_url       VARCHAR(500),
    status          VARCHAR(20) NOT NULL,
    display_order   INTEGER NOT NULL,
    parent_id       BIGINT REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT uk_categories_name    UNIQUE (name),
    CONSTRAINT uk_categories_slug    UNIQUE (slug),
    CONSTRAINT ck_categories_status  CHECK (status IN ('ACTIVE', 'ARCHIVED'))
);

CREATE TABLE creator_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    user_id             BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    display_name        VARCHAR(100) NOT NULL,
    slug                VARCHAR(60) NOT NULL,
    bio                 VARCHAR(500),
    avatar_url          VARCHAR(500),
    banner_url          VARCHAR(500),
    primary_category_id BIGINT REFERENCES categories (id) ON DELETE RESTRICT,
    status              VARCHAR(20) NOT NULL,
    CONSTRAINT uk_creator_profiles_user   UNIQUE (user_id),
    CONSTRAINT uk_creator_profiles_slug   UNIQUE (slug),
    CONSTRAINT ck_creator_profiles_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED'))
);
