CREATE TABLE moderation_reports (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    reporter_id         BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    target_type         VARCHAR(20) NOT NULL,
    target_user_id      BIGINT REFERENCES users (id) ON DELETE RESTRICT,
    target_chain_id     BIGINT REFERENCES creator_profiles (id) ON DELETE RESTRICT,
    target_stream_id    BIGINT REFERENCES streams (id) ON DELETE RESTRICT,
    target_video_id     BIGINT REFERENCES videos (id) ON DELETE RESTRICT,
    target_clip_id      BIGINT REFERENCES clips (id) ON DELETE RESTRICT,
    target_message_id   BIGINT REFERENCES chat_messages (id) ON DELETE RESTRICT,
    reason              VARCHAR(20) NOT NULL,
    description         VARCHAR(2000),
    status              VARCHAR(20) NOT NULL,
    CONSTRAINT ck_reports_target  CHECK (target_type IN ('USER', 'CHAIN', 'STREAM', 'VIDEO', 'CLIP', 'CHAT_MESSAGE')),
    CONSTRAINT ck_reports_reason  CHECK (reason IN ('SPAM', 'HARASSMENT', 'HATE', 'SEXUAL', 'VIOLENCE', 'COPYRIGHT', 'OTHER')),
    CONSTRAINT ck_reports_status  CHECK (status IN ('OPEN', 'ACCEPTED', 'REJECTED'))
);

CREATE INDEX idx_reports_status_created  ON moderation_reports (status, created_at);
CREATE INDEX idx_reports_reporter        ON moderation_reports (reporter_id);

CREATE TABLE moderation_actions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    report_id       BIGINT REFERENCES moderation_reports (id) ON DELETE RESTRICT,
    moderator_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    target_user_id  BIGINT REFERENCES users (id) ON DELETE RESTRICT,
    action          VARCHAR(20) NOT NULL,
    scope           VARCHAR(20) NOT NULL,
    reason          VARCHAR(500) NOT NULL,
    starts_at       TIMESTAMPTZ,
    ends_at         TIMESTAMPTZ,
    state           VARCHAR(20) NOT NULL,
    CONSTRAINT ck_actions_action  CHECK (action IN ('DISMISS', 'WARN', 'TIMEOUT', 'HIDE_CONTENT',
        'SUSPEND_CHAIN', 'BAN_TEMP', 'BAN_PERM')),
    CONSTRAINT ck_actions_scope   CHECK (scope IN ('MESSAGE', 'CONTENT', 'CHAIN', 'ACCOUNT', 'PLATFORM')),
    CONSTRAINT ck_actions_state   CHECK (state IN ('ACTIVE', 'LIFTED', 'EXPIRED'))
);

CREATE INDEX idx_actions_target_state  ON moderation_actions (target_user_id, state);
CREATE INDEX idx_actions_moderator     ON moderation_actions (moderator_id);
CREATE INDEX idx_actions_report        ON moderation_actions (report_id);
