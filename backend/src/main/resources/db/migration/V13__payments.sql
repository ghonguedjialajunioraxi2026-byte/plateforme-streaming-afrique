-- ============================================================
-- V13__payments.sql — entrées fiat multi-prestataires + remboursements (7.22).
-- Dépend de : V1 (users). Mobile Money (Wave/Orange/MTN/M-Pesa), cartes,
-- virement, internationaux — couple méthode + prestataire extensible.
-- INTERDIT : PAN/CVV/numéros complets (seul un masque partiel est stocké).
-- Remboursement = lignes dédiées, jamais d'UPDATE destructeur.
-- ============================================================

CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    payer_id        BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    internal_ref    VARCHAR(100) NOT NULL,
    provider_ref    VARCHAR(200),
    fiat_amount     NUMERIC(19, 4) NOT NULL,
    -- VARCHAR(3) et non CHAR(3) : l'entité mappe un String (validate Hibernate).
    fiat_currency   VARCHAR(3) NOT NULL,
    coins_credited  BIGINT NOT NULL,
    method          VARCHAR(20) NOT NULL,
    provider        VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    account_masked  VARCHAR(50),
    metadata        VARCHAR(2000),
    failure_reason  VARCHAR(500),
    CONSTRAINT uk_payments_internal_ref   UNIQUE (internal_ref),
    CONSTRAINT uk_payments_provider_ref   UNIQUE (provider_ref),
    CONSTRAINT ck_payments_amounts        CHECK (fiat_amount > 0 AND coins_credited > 0),
    CONSTRAINT ck_payments_currency       CHECK (fiat_currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_payments_method         CHECK (method IN ('MOBILE_MONEY', 'CARD', 'BANK_TRANSFER', 'OTHER')),
    CONSTRAINT ck_payments_provider       CHECK (provider IN ('WAVE', 'ORANGE_MONEY', 'MTN_MOMO', 'MPESA',
        'STRIPE', 'PAYSTACK', 'FLUTTERWAVE', 'OTHER')),
    CONSTRAINT ck_payments_status         CHECK (status IN ('INITIATED', 'PENDING', 'CONFIRMED',
        'FAILED', 'CANCELLED', 'REFUNDED'))
);

CREATE INDEX idx_payments_payer_status ON payments (payer_id, status);

CREATE TABLE payment_refunds (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    payment_id      BIGINT NOT NULL REFERENCES payments (id) ON DELETE RESTRICT,
    fiat_amount     NUMERIC(19, 4) NOT NULL,
    coins_debited   BIGINT NOT NULL,
    reason          VARCHAR(500) NOT NULL,
    provider_ref    VARCHAR(200),
    status          VARCHAR(20) NOT NULL,
    CONSTRAINT ck_refunds_amounts CHECK (fiat_amount > 0 AND coins_debited > 0),
    CONSTRAINT ck_refunds_status  CHECK (status IN ('REQUESTED', 'SENT', 'FAILED'))
);

CREATE INDEX idx_refunds_payment ON payment_refunds (payment_id);
