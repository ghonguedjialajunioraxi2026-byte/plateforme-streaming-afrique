CREATE TABLE subscription_plans (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    name            VARCHAR(100) NOT NULL,
    price_coins     BIGINT NOT NULL,
    duration_days   INTEGER NOT NULL,
    perks           VARCHAR(2000),
    active          BOOLEAN NOT NULL,
    CONSTRAINT uk_subscription_plans_name   UNIQUE (name),
    CONSTRAINT ck_subscription_plans_price   CHECK (price_coins > 0),
    CONSTRAINT ck_subscription_plans_days    CHECK (duration_days > 0)
);

CREATE TABLE subscriptions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ NOT NULL,
    subscriber_id           BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    creator_id              BIGINT NOT NULL REFERENCES creator_profiles (id) ON DELETE RESTRICT,
    plan_id                 BIGINT NOT NULL REFERENCES subscription_plans (id) ON DELETE RESTRICT,
    status                  VARCHAR(20) NOT NULL,
    current_period_start    TIMESTAMPTZ NOT NULL,
    current_period_end      TIMESTAMPTZ NOT NULL,
    auto_renew              BOOLEAN NOT NULL,
    CONSTRAINT ck_subscriptions_status  CHECK (status IN ('ACTIVE', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_subscriptions_period  CHECK (current_period_end > current_period_start)
);

CREATE INDEX idx_subscriptions_subscriber          ON subscriptions (subscriber_id);
CREATE INDEX idx_subscriptions_subscriber_status  ON subscriptions (subscriber_id, status);
CREATE INDEX idx_subscriptions_creator            ON subscriptions (creator_id);
CREATE INDEX idx_subscriptions_creator_status    ON subscriptions (creator_id, status);
