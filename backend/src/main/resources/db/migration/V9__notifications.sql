CREATE TABLE notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    recipient_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    type            VARCHAR(30) NOT NULL,
    title           VARCHAR(150) NOT NULL,
    message         VARCHAR(500) NOT NULL,
    link_url        VARCHAR(500),
    payload         VARCHAR(2000),
    is_read         BOOLEAN NOT NULL,
    CONSTRAINT ck_notifications_type CHECK (type IN ('NEW_FOLLOWER', 'SUBSCRIPTION', 'STREAM_STARTED',
        'NEW_VIDEO', 'NEW_CLIP', 'REPLY', 'MENTION', 'GIFT', 'PAYMENT', 'MODERATION', 'SYSTEM'))
);

CREATE INDEX idx_notifications_recipient_read     ON notifications (recipient_id, is_read);
CREATE INDEX idx_notifications_recipient_created  ON notifications (recipient_id, created_at);
CREATE INDEX idx_notifications_recipient_type     ON notifications (recipient_id, type);
