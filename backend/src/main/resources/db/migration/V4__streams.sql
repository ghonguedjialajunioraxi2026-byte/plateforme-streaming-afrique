-- Métier : cycle SCHEDULED→LIVE→ENDED, visibilité, pic (seul compteur
-- persisté ; l'instantané vit en Redis). Technique : empreinte de clé
-- (JAMAIS en clair), protocole, URL de lecture — sessions d'ingest et
-- viewers courants hors base (serveur média + Redis).
-- ============================================================

CREATE TABLE streams (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    creator_id          BIGINT NOT NULL REFERENCES creator_profiles (id) ON DELETE RESTRICT,
    category_id         BIGINT REFERENCES categories (id) ON DELETE RESTRICT,
    title               VARCHAR(120) NOT NULL,
    description         VARCHAR(2000),
    status              VARCHAR(20) NOT NULL,
    visibility          VARCHAR(20) NOT NULL,
    thumbnail_url       VARCHAR(500),
    language            VARCHAR(10),
    peak_viewers        INTEGER NOT NULL,
    deleted             BOOLEAN NOT NULL,
    stream_key_hash     VARCHAR(128),
    ingest_protocol     VARCHAR(20),
    playback_url        VARCHAR(500),
    scheduled_start_at  TIMESTAMPTZ,
    started_at          TIMESTAMPTZ,
    ended_at            TIMESTAMPTZ,
    CONSTRAINT ck_streams_status      CHECK (status IN ('SCHEDULED', 'LIVE', 'ENDED')),
    CONSTRAINT ck_streams_visibility  CHECK (visibility IN ('PUBLIC', 'UNLISTED', 'PRIVATE')),
    CONSTRAINT ck_streams_ingest      CHECK (ingest_protocol IS NULL OR ingest_protocol IN ('RTMP', 'WEBRTC')),
    CONSTRAINT ck_streams_peak        CHECK (peak_viewers >= 0)
);

-- Lives actifs : requête la plus chaude (accueil "en direct").
CREATE INDEX idx_streams_creator          ON streams (creator_id);
CREATE INDEX idx_streams_creator_status   ON streams (creator_id, status);
CREATE INDEX idx_streams_category         ON streams (category_id);
CREATE INDEX idx_streams_status           ON streams (status);
CREATE INDEX idx_streams_status_started   ON streams (status, started_at);
CREATE INDEX idx_streams_scheduled_start  ON streams (scheduled_start_at);
