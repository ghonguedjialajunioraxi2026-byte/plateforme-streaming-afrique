-- Dépend de : V3 (creator_profiles, categories), V4 (streams, origine).
-- AUCUN blob : storage_key (bucket futur) + video_url (diffusion).
-- AUCUN compteur de vues stocké (watch_history + stat_snapshots).
-- ============================================================

CREATE TABLE videos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL,
    creator_id          BIGINT NOT NULL REFERENCES creator_profiles (id) ON DELETE RESTRICT,
    category_id         BIGINT REFERENCES categories (id) ON DELETE RESTRICT,
    origin_stream_id    BIGINT REFERENCES streams (id) ON DELETE RESTRICT,
    title               VARCHAR(150) NOT NULL,
    description         VARCHAR(2000),
    video_url           VARCHAR(500) NOT NULL,
    storage_key         VARCHAR(500),
    thumbnail_url       VARCHAR(500),
    duration_seconds    INTEGER NOT NULL,
    visibility          VARCHAR(20) NOT NULL,
    processing_status   VARCHAR(20) NOT NULL,
    deleted             BOOLEAN NOT NULL,
    published_at        TIMESTAMPTZ,
    CONSTRAINT ck_videos_visibility   CHECK (visibility IN ('PUBLIC', 'UNLISTED', 'PRIVATE')),
    CONSTRAINT ck_videos_processing   CHECK (processing_status IN ('UPLOADED', 'PROCESSING', 'READY', 'FAILED')),
    CONSTRAINT ck_videos_duration     CHECK (duration_seconds > 0)
);

CREATE INDEX idx_videos_creator                        ON videos (creator_id);
CREATE INDEX idx_videos_creator_visibility_published   ON videos (creator_id, visibility, published_at);
CREATE INDEX idx_videos_category                       ON videos (category_id);
CREATE INDEX idx_videos_origin_stream                  ON videos (origin_stream_id);
CREATE INDEX idx_videos_published_at                   ON videos (published_at);
