-- V17__auth_sessions_tokens.sql — authentification complète (ÉTAPE 08).
-- AUCUNE migration existante modifiée (règle 7.x) : uniquement ADD et CREATE.
--
-- 1. users.email_verified : FALSE par défaut (comptes existants = non vérifiés,
--    aucun blocage fonctionnel — le login n'en dépend pas).
-- 2. auth_sessions : sessions/appareils = refresh tokens RÉVOQUABLES.
--    Seule l'EMPREINTE SHA-256 du refresh JWT est stockée (jamais le brut) ;
--    la rotation crée une ligne et révoque l'ancienne.
-- 3. email_tokens : jetons à usage unique (vérification email 24 h,
--    reset mot de passe 1 h). Empreinte SHA-256 stockée, brut remis une
--    seule fois au client (lien / réponse dev).
-- ============================================================

ALTER TABLE users
    ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE auth_sessions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    user_id         BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    token_hash      VARCHAR(64) NOT NULL,
    device_info     VARCHAR(200),
    ip_address      VARCHAR(45),
    last_used_at    TIMESTAMPTZ NOT NULL,
    expires_at      TIMESTAMPTZ NOT NULL,
    revoked_at      TIMESTAMPTZ,
    CONSTRAINT uk_auth_sessions_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_auth_sessions_user_active ON auth_sessions (user_id, revoked_at);

CREATE TABLE email_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    user_id         BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    token_hash      VARCHAR(64) NOT NULL,
    type            VARCHAR(20) NOT NULL,
    expires_at      TIMESTAMPTZ NOT NULL,
    used_at         TIMESTAMPTZ,
    CONSTRAINT uk_email_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_email_tokens_type  CHECK (type IN ('VERIFY_EMAIL', 'PASSWORD_RESET'))
);

CREATE INDEX idx_email_tokens_user_type ON email_tokens (user_id, type);
