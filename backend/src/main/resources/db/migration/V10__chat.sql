-- V10__chat.sql — persistance du chat, vérité + historique (7.18).
-- Dépend de : V1 (users), V4 (streams). Salon implicite = stream_id.
-- author_id NULL réservé aux messages système. Corps immuable
-- (modération = HIDDEN + motif). created_at EST l'horodatage.
-- Un seul index chaud (stream_id, id) : lecture keyset, INSERT non taxé.
-- Candidat n°1 au partitionnement mensuel futur.
-- ============================================================

CREATE TABLE chat_messages (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ NOT NULL,
    stream_id               BIGINT NOT NULL REFERENCES streams (id) ON DELETE RESTRICT,
    author_id               BIGINT REFERENCES users (id) ON DELETE RESTRICT,
    author_name_snapshot    VARCHAR(100) NOT NULL,
    body_raw                VARCHAR(2000) NOT NULL,
    body_display            VARCHAR(2000) NOT NULL,
    system                  BOOLEAN NOT NULL,
    status                  VARCHAR(20) NOT NULL,
    hidden_reason           VARCHAR(200),
    CONSTRAINT ck_chat_status CHECK (status IN ('VISIBLE', 'HIDDEN'))
);

CREATE INDEX idx_chat_stream_id ON chat_messages (stream_id, id);
