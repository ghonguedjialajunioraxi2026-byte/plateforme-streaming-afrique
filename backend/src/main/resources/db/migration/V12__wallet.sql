-- ============================================================
-- V12__wallet.sql — monnaie interne, portefeuilles, cadeaux, journal (7.21).
-- Dépend de : V1 (users), V4 (streams).
-- Précision : coins en BIGINT d'unités minimales (arithmétique exacte) ;
-- fiat uniquement en RÉFÉRENCE NUMERIC(19,4) + code ISO. Journal
-- append-only (contre-passation, jamais d'UPDATE). Idempotence via clé
-- unique. Soldes = cache recalculable, jamais négatifs (CHECK).
-- ============================================================

CREATE TABLE currencies (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                  TIMESTAMPTZ NOT NULL,
    updated_at                  TIMESTAMPTZ NOT NULL,
    code                        VARCHAR(20) NOT NULL,
    name                        VARCHAR(100) NOT NULL,
    -- Nomenclature Hibernate : buyRateFiatPer1000 → buy_rate_fiat_per1000
    -- (pas d'underscore devant les chiffres).
    buy_rate_fiat_per1000       NUMERIC(19, 4) NOT NULL,
    payout_rate_fiat_per1000    NUMERIC(19, 4) NOT NULL,
    fee_bps                     INTEGER NOT NULL,
    effective_from              TIMESTAMPTZ NOT NULL,
    current                     BOOLEAN NOT NULL,
    CONSTRAINT ck_currencies_rates  CHECK (buy_rate_fiat_per1000 > 0 AND payout_rate_fiat_per1000 > 0),
    CONSTRAINT ck_currencies_fee    CHECK (fee_bps >= 0 AND fee_bps <= 10000)
);

CREATE INDEX idx_currencies_code_effective ON currencies (code, effective_from);

CREATE TABLE wallets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    owner_id        BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    balance_coins   BIGINT NOT NULL,
    reserved_coins  BIGINT NOT NULL,
    status          VARCHAR(20) NOT NULL,
    CONSTRAINT uk_wallets_owner   UNIQUE (owner_id),
    CONSTRAINT ck_wallets_status  CHECK (status IN ('ACTIVE', 'FROZEN')),
    CONSTRAINT ck_wallets_balances CHECK (balance_coins >= 0 AND reserved_coins >= 0
        AND reserved_coins <= balance_coins)
);

CREATE TABLE gift_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    name            VARCHAR(100) NOT NULL,
    price_coins     BIGINT NOT NULL,
    animation_ref   VARCHAR(200),
    active          BOOLEAN NOT NULL,
    CONSTRAINT uk_gift_items_name   UNIQUE (name),
    CONSTRAINT ck_gift_items_price  CHECK (price_coins > 0)
);

CREATE TABLE gift_sends (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ NOT NULL,
    gift_id                 BIGINT NOT NULL REFERENCES gift_items (id) ON DELETE RESTRICT,
    sender_id               BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    stream_id               BIGINT NOT NULL REFERENCES streams (id) ON DELETE RESTRICT,
    quantity                INTEGER NOT NULL,
    total_cost_coins        BIGINT NOT NULL,
    creator_share_coins     BIGINT NOT NULL,
    CONSTRAINT ck_giftsends_qty   CHECK (quantity > 0),
    CONSTRAINT ck_giftsends_cost  CHECK (total_cost_coins > 0 AND creator_share_coins >= 0
        AND creator_share_coins <= total_cost_coins)
);

CREATE INDEX idx_giftsends_stream  ON gift_sends (stream_id, id);
CREATE INDEX idx_giftsends_sender  ON gift_sends (sender_id);

CREATE TABLE transactions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ NOT NULL,
    idempotency_key         VARCHAR(100) NOT NULL,
    wallet_id               BIGINT NOT NULL REFERENCES wallets (id) ON DELETE RESTRICT,
    direction               VARCHAR(10) NOT NULL,
    amount_coins            BIGINT NOT NULL,
    -- VARCHAR(3) et non CHAR(3) : l'entité mappe un String (validate Hibernate).
    fiat_reference_amount   NUMERIC(19, 4),
    fiat_currency           VARCHAR(3),
    balance_before          BIGINT NOT NULL,
    balance_after           BIGINT NOT NULL,
    kind                    VARCHAR(30) NOT NULL,
    status                  VARCHAR(20) NOT NULL,
    reference               VARCHAR(200),
    CONSTRAINT uk_tx_idempotency  UNIQUE (idempotency_key),
    CONSTRAINT ck_tx_direction    CHECK (direction IN ('CREDIT', 'DEBIT')),
    CONSTRAINT ck_tx_amounts      CHECK (amount_coins > 0 AND balance_before >= 0 AND balance_after >= 0),
    CONSTRAINT ck_tx_kind         CHECK (kind IN ('COIN_PURCHASE', 'GIFT_SEND', 'GIFT_RECEIPT', 'FEE',
        'SUBSCRIPTION_CHARGE', 'SUBSCRIPTION_PAYOUT', 'WITHDRAWAL', 'REFUND', 'AD_PAYOUT')),
    CONSTRAINT ck_tx_status       CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REVERSED'))
);

CREATE INDEX idx_tx_wallet_id ON transactions (wallet_id, id);
