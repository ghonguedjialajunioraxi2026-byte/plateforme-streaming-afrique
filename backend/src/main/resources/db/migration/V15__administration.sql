CREATE TABLE admin_audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    actor_id        BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    action          VARCHAR(100) NOT NULL,
    target_type     VARCHAR(30) NOT NULL,
    target_id       BIGINT,
    before_json     VARCHAR(2000),
    after_json      VARCHAR(2000),
    reason          VARCHAR(500)
);

CREATE INDEX idx_audit_actor_created  ON admin_audit_log (actor_id, created_at);
CREATE INDEX idx_audit_target         ON admin_audit_log (target_type, target_id);

CREATE TABLE app_config (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    config_key      VARCHAR(100) NOT NULL,
    config_value    VARCHAR(2000) NOT NULL,
    version         INTEGER NOT NULL,
    effective_from  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_config_key_version UNIQUE (config_key, version),
    CONSTRAINT ck_config_version CHECK (version > 0)
);

CREATE INDEX idx_config_key ON app_config (config_key);

